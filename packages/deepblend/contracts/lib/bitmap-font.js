/** Glyph cell size in pixels, before scaling. */
export const GLYPH_WIDTH = 5
export const GLYPH_HEIGHT = 7
/** One blank column between glyphs. */
const GLYPH_ADVANCE = GLYPH_WIDTH + 1

/** The character drawn for anything the font has no glyph for. */
const FALLBACK = '?'

/**
 * Measure the text width at a given scale.
 *
 * @param {string} text
 * @param {number} scale
 * @returns {number}
 */
export function textWidth(text, scale = 1) {
  if (text.length === 0) return 0
  return (text.length * GLYPH_ADVANCE - 1) * scale
}

/**
 * Draw text with the top-left corner at (x, y). Uppercases its input, because the
 * font has only one case and silently drawing blanks for lowercase would be worse
 * than the visible transformation.
 *
 * @param {import('./png.js').RgbaImage} image
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {[number, number, number, number]} color
 * @param {number} [scale]
 */
export function drawText(image, text, x, y, color, scale = 1) {
  const upper = text.toUpperCase()
  let cursor = x
  for (const character of upper) {
    const glyph = GLYPHS[character] ?? GLYPHS[FALLBACK]
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      const bits = glyph[row]
      for (let column = 0; column < GLYPH_WIDTH; column += 1) {
        // The set high bit is the padding marker, never a pixel: reading the
        // glyph's own 5 data bits means a row written with the wrong length
        // still cannot produce stray pixels to the right of the glyph.
        const on = (bits >> (GLYPH_WIDTH - 1 - column)) & 1
        if (on === 0) continue
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            setPixel(image, cursor + column * scale + dx, y + row * scale + dy, color)
          }
        }
      }
    }
    cursor += GLYPH_ADVANCE * scale
  }
}

/**
 * Write one pixel, ignoring anything outside the image.
 *
 * @param {import('./png.js').RgbaImage} image
 * @param {number} x
 * @param {number} y
 * @param {[number, number, number, number]} color
 */
function setPixel(image, x, y, color) {
  if (x < 0 || y < 0 || x >= image.width || y >= image.height) return
  const offset = (y * image.width + x) * 4
  image.data[offset] = color[0]
  image.data[offset + 1] = color[1]
  image.data[offset + 2] = color[2]
  image.data[offset + 3] = color[3]
}
