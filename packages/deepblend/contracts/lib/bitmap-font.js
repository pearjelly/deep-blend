/**
 * A 5x7 bitmap font, for labelling contact-sheet cells.
 *
 * WHY A FONT IS IN THE CONTRACTS PACKAGE AT ALL
 * --------------------------------------------
 * A contact sheet without labels forces the model to guess which cell is which
 * view. It *could* guess — the cells come back in a documented order — but the one
 * thing a vision review must not do is mislabel its own evidence: an occlusion
 * reported against "the top view" that is actually the three-quarter view produces
 * a confident, well-formed, wrong patch. A label removes the guess.
 *
 * The alternative was an image library with real text rendering, which is the
 * dependency this design exists to avoid (see `png.js`). 5x7 uppercase glyphs are
 * about forty lines of data and are unambiguous at 2x scale inside a 1600px sheet.
 *
 * Each glyph is 7 rows of 5 bits, most significant bit on the left. Every row is
 * OR'd with `0b1000000`, which both pads to a byte and makes a truncated or
 * mistyped row visibly wrong rather than a plausible shorter one.
 *
 * Owner: DeepBlend Studio — M2
 */

