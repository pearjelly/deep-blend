#!/usr/bin/env node
/** Generate declaration shapes from the authoritative schemas; no third-party generator. */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { BlenderErrorCode, BlenderWarningCode } from '../../packages/deepblend/contracts/lib/index.js'

const documents = [
  ['scene-spec', 'SceneSpecSchema', 'SceneSpec'],
  ['scene-patch', 'ScenePatchSchema', 'ScenePatch'],
  ['recipe', 'RecipeSchema', 'RecipeManifest'],
]
const nameOf = name => name.replace(/(^|[-_])([a-z])/g, (_, separator, letter) => letter.toUpperCase())
function declaration(schema, namespace, definitions) {
  if (schema.$ref) {
    const key = schema.$ref.match(/^#\/\$defs\/([^/]+)$/)?.[1]
    if (!key || !Object.hasOwn(definitions, key)) throw new Error(`Unsupported or missing schema reference ${schema.$ref}`)
    return `${namespace}.${nameOf(key)}`
  }
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ')
  if (schema.oneOf) return schema.oneOf.map(branch => `(${declaration(branch, namespace, definitions)})`).join(' | ')
  if (Array.isArray(schema.type)) return schema.type.map(type => declaration({ ...schema, type }, namespace, definitions)).join(' | ')
  if (schema.type === 'string' || schema.type === 'boolean' || schema.type === 'null') return schema.type
  if (schema.type === 'number' || schema.type === 'integer') return 'number'
  if (schema.type === 'array') {
    const item = declaration(schema.items, namespace, definitions)
    if (schema.minItems === schema.maxItems && Number.isInteger(schema.minItems) && schema.minItems <= 16) {
      return `[${Array.from({ length: schema.minItems }, () => item).join(', ')}]`
    }
    return `Array<${item}>`
  }
  if (schema.type === 'object') {
    const required = new Set(schema.required ?? [])
    const fields = Object.entries(schema.properties ?? {}).map(([key, value]) =>
      `${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${declaration(value, namespace, definitions)};`)
    if (schema.additionalProperties !== false) {
      fields.push(`[key: string]: ${typeof schema.additionalProperties === 'object'
        ? declaration(schema.additionalProperties, namespace, definitions) : 'unknown'};`)
    }
    return `{ ${fields.join(' ')} }`
  }
  throw new Error(`Unsupported declaration schema ${JSON.stringify(schema)}`)
}
const chunks = ['/** Generated by deepblend/tools/generate-sdk-types.mjs. Do not edit.',
  ' * Types describe JSON shape. Numeric bounds, ID grammar and references still require validation. */']
for (const [file, namespace, alias] of documents) {
  const bytes = readFileSync(new URL(`../schemas/${file}.schema.json`, import.meta.url))
  const schema = JSON.parse(bytes)
  const definitions = schema.$defs ?? {}
  chunks.push(`\n/** Source SHA-256: ${createHash('sha256').update(bytes).digest('hex')} */`, `export namespace ${namespace} {`)
  for (const [name, definition] of Object.entries(definitions)) {
    chunks.push(`  export type ${nameOf(name)} = ${declaration(definition, namespace, definitions)};`)
  }
  chunks.push(`  export type Document = ${declaration(schema, namespace, definitions)};`, '}', `export type ${alias} = ${namespace}.Document;`)
}
for (const [alias, name] of Object.entries({ Entity: 'Entity', Generator: 'Generator', ModelModifier: 'ModelModifier',
  Material: 'Material', Asset: 'Asset', Camera: 'Camera', Light: 'Light', Transform: 'Transform',
  AnimationTrack: 'AnimationTrack', RenderProfile: 'RenderProfile', ReferenceImage: 'ReferenceImage',
  MaterialBinding: 'MaterialBinding', MaterialTangent: 'MaterialTangent', Vec3: 'Vec3' })) {
  chunks.push(`export type ${alias} = SceneSpecSchema.${name};`)
}
chunks.push('export type ScenePatchOperation = ScenePatchSchema.Operation;',
  'export type RecipeCapability = RecipeManifest["compatibility"]["capabilities"][number];')
for (const [name, values] of [['BlenderErrorCodeMap', BlenderErrorCode], ['BlenderWarningCodeMap', BlenderWarningCode]]) {
  chunks.push(`export interface ${name} {`, ...Object.entries(values).map(([key, value]) => `  readonly ${key}: ${JSON.stringify(value)};`), '}')
}
const output = `${chunks.join('\n')}\n`
const path = fileURLToPath(new URL('../../packages/deepblend/contracts/lib/schema-types.d.ts', import.meta.url))
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('SDK declarations differ from their schemas; run generate-sdk-types.mjs')
  console.log('SDK schema declarations match all three source schemas and error vocabularies.')
} else {
  writeFileSync(path, output)
  console.log('Generated SDK schema declarations.')
}
